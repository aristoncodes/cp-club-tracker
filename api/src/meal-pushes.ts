const MEAL_SECOND_OF_DAY: Record<Meal, number> = {
  breakfast: 3.5 * 3600,
  lunch: 7.5 * 3600,
  snacks: 11.5 * 3600,
  dinner: 15.5 * 3600,
};

const CRON_TICK = 60;
const DAY = 86400;
const MIN_PEERS_TO_MENTION = 2;

export function mealAt(now: number): Meal | null {
  const second = now % DAY;
  return MEAL_ORDER.find((meal) => second >= MEAL_SECOND_OF_DAY[meal] && second < MEAL_SECOND_OF_DAY[meal] + CRON_TICK) ?? null;
}

// A person sees breakfast's line whether or not they have solved, because "yesterday's problem" fits both.
export function mealPush(meal: Meal, day: number, solvedToday: boolean, peersSolved: number): { title: string; body: string } {
  const pool = meal !== 'breakfast' && solvedToday ? SOLVED_LINES : MEAL_LINES[meal];
  const index = pool === SOLVED_LINES ? day * 3 + MEAL_ORDER.indexOf(meal) : day;
  const [title, body] = pool[index % pool.length];
  const peers = !solvedToday && peersSolved >= MIN_PEERS_TO_MENTION ? ` ${peersSolved} clubmates already have.` : '';
  return { title, body: meal === 'breakfast' ? body : body + peers };
}
